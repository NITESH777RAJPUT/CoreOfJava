public class RelationalOperators {

    public static void main(String[] args) {
        // Relational operators in Java --> ==, !=, >, <, >=, <=

        int a = 10; // This line declares an integer variable 'a' and initializes it with the value 10
        int b = 5; // This line declares an integer variable 'b' and initializes it with the value 5

        boolean isEqual = (a == b); // This line checks if 'a' is equal to 'b' and assigns the result to 'isEqual'
        System.out.println("Is Equal: " + isEqual); // This line prints the value of 'isEqual' to the console

        boolean isNotEqual = (a != b); // This line checks if 'a' is not equal to 'b' and assigns the result to 'isNotEqual'
        System.out.println("Is Not Equal: " + isNotEqual); // This line prints the value of 'isNotEqual' to the console

        boolean isGreaterThan = (a > b); // This line checks if 'a' is greater than 'b' and assigns the result to 'isGreaterThan'
        System.out.println("Is Greater Than: " + isGreaterThan); // This line prints the value of 'isGreaterThan' to the console

        boolean isLessThan = (a < b); // This line checks if 'a' is less than 'b' and assigns the result to 'isLessThan'
        System.out.println("Is Less Than: " + isLessThan); // This line prints the value of 'isLessThan' to the console

        boolean isGreaterThanOrEqual = (a >= b); // This line checks if 'a' is greater than or equal to 'b' and assigns the result to 'isGreaterThanOrEqual'
        System.out.println("Is Greater Than or Equal: " + isGreaterThanOrEqual); // This line prints the value of 'isGreaterThanOrEqual' to the console

        boolean isLessThanOrEqual = (a <= b); // This line checks if 'a' is less than or equal to 'b' and assigns the result to 'isLessThanOrEqual'
        System.out.println("Is Less Than or Equal: " + isLessThanOrEqual); // This line prints the value of 'isLessThanOrEqual'


    }
} 